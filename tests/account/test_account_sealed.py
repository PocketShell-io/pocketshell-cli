def test_default_path_is_unchanged_without_opt_in(monkeypatch):
    monkeypatch.delenv(sealed.ENV_SEALED, raising=False)
    called = []

    def fake_opener(*handlers):
        called.append(True)
        raise AssertionError("stop here")

    monkeypatch.setattr(client, "token_opener", fake_opener)
    monkeypatch.setattr(client, "_sealed_opener", lambda: (_ for _ in ()).throw(AssertionError("sealed used")))
    with pytest.raises(AssertionError, match="stop here"):
        client.start_device(DEFAULT_BROKER_URL, "x")
    assert called


def test_sealed_opener_uses_environment_proxy_but_refuses_redirects(monkeypatch):
    monkeypatch.setenv("HTTPS_PROXY", "http://127.0.0.1:9")
    opener = client._sealed_opener()
    names = {type(h).__name__ for h in opener.handlers}
    assert "ProxyHandler" in names and "_NoRedirect" in names
    proxy = next(h for h in opener.handlers if type(h).__name__ == "ProxyHandler")
    assert proxy.proxies.get("https") == "http://127.0.0.1:9"
