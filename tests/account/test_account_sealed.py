"""Sealed broker transport (pocketshell.account.sealed) — synthetic secrets only.

Covers: byte-for-byte interop with the broker's Node implementation (vector
generated by pocketshell-sync tests/test-sealed.mjs), an intercepting fake proxy
that records every byte the real client sends and receives, a wrong-key broker,
tampering, no fallback to the plain path, and the opt-in/pin/origin rules.
"""

from __future__ import annotations

import hashlib
import hmac
import io
import json
import secrets
import urllib.request
from pathlib import Path

import pytest
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

from pocketshell.account import broker as client
from pocketshell.account import sealed
from pocketshell.account.config import DEFAULT_BROKER_URL
from pocketshell.account.errors import AccountError, BrokerUnavailable

VECTOR = json.loads((Path(__file__).parent / "fixtures" / "sealed-v1-vector.json").read_text())
SUITE = sealed._SUITE
DEVICE_CODE = "DC" + "x" * 40  # synthetic
SESSION_TOKEN = "psc_" + "T" * 43  # synthetic


def _broker_keys(ikm: bytes):
    pair = SUITE.kem.derive_key_pair(ikm)
    pub = pair.public_key.to_public_bytes()
    return pair, pub, sealed.key_id(pub)


class FakeBroker:
    """Broker + intercepting proxy in one: records the wire, answers sealed."""

    def __init__(self, ikm: bytes | None = None, *, tamper: bool = False, plain_status=200):
        self.pair, self.pub, self.kid = _broker_keys(ikm or secrets.token_bytes(32))
        self.wire: list[tuple[str, dict, bytes, bytes]] = []  # url, headers, req, resp
        self.inner_seen: list[dict] = []
        self.tamper = tamper
        self.respond = lambda inner: (200, json.dumps({"device_code": DEVICE_CODE, "user_code": "BCDF-GHJK",
                                                       "expires_in": 600, "interval": 5}))

    def pins(self):
        return {self.kid: sealed._b64u(self.pub)}

    def open(self, req, timeout=None):
        body = req.data
        env = json.loads(body)
        enc = sealed._unb64u(env["enc"])
        kid_b = env["kid"].encode()
        ctx = SUITE.create_recipient_context(enc, self.pair.private_key, sealed.REQ_INFO + b"\x00" + kid_b)
        inner = json.loads(ctx.open(sealed._unb64u(env["ct"]), aad=kid_b))
        self.inner_seen.append(inner)
        status, text = self.respond(inner)
        secret = ctx.export(sealed.RES_EXPORT, 16)
        nonce = secrets.token_bytes(16)
        prk = hmac.new(enc + nonce, secret, hashlib.sha256).digest()
        key = hmac.new(prk, b"key\x01", hashlib.sha256).digest()[:16]
        iv = hmac.new(prk, b"nonce\x01", hashlib.sha256).digest()[:12]
        ct = AESGCM(key).encrypt(iv, json.dumps({"s": status, "b": text}).encode(), b"")
        if self.tamper:
            ct = ct[:-1] + bytes([ct[-1] ^ 1])
        out = json.dumps({"v": 1, "nonce": sealed._b64u(nonce), "ct": sealed._b64u(ct)}).encode()
        self.wire.append((req.full_url, dict(req.header_items()), body, out))
        return _Resp(out)


class _Resp(io.BytesIO):
    status = 200

    def close(self):  # noqa: D401
        super().close()


@pytest.fixture
def sealed_env(monkeypatch):
    monkeypatch.setenv(sealed.ENV_SEALED, "1")
    # Any plain-path attempt is a bug: it would put secrets in front of the proxy.
    def no_plain(*a, **k):
        raise AssertionError("fell back to the plain (proxy-visible) path")
    monkeypatch.setattr(client, "token_opener", no_plain)


def _install(monkeypatch, fake: FakeBroker):
    monkeypatch.setattr(client, "_sealed_opener", lambda: fake)
    monkeypatch.setattr(sealed, "PINNED_KEYS", fake.pins())


def test_vector_interop_with_the_node_broker():
    eks = SUITE.kem.derive_key_pair(sealed._unb64u(VECTOR["ekm_b64u"]))
    i = VECTOR["inner"]
    req = sealed.seal(i["m"], i["p"], body=i["b"], bearer=None, pins={VECTOR["kid"]: VECTOR["server_pk_b64u"]},
                      now=i["t"], nonce=sealed._unb64u(i["n"]), ephemeral=eks)
    assert req.body.decode() == VECTOR["request_body"], "request bytes match the Node implementation"
    status, body = req.open(VECTOR["response_body"].encode())
    assert (status, json.loads(body)) == (200, {"synthetic": "response-body"})


def test_start_device_through_an_intercepting_proxy_discloses_nothing(sealed_env, monkeypatch):
    fake = FakeBroker()
    _install(monkeypatch, fake)
    start = client.start_device(DEFAULT_BROKER_URL, "synthetic@cloud")
    assert start.device_code == DEVICE_CODE and start.user_code == "BCDF-GHJK"
    url, headers, req_body, resp_body = fake.wire[0]
    assert url == DEFAULT_BROKER_URL + "/sealed"
    everything = url.encode() + json.dumps(headers).encode() + req_body + resp_body
    for secret in (DEVICE_CODE, "BCDF-GHJK", "synthetic@cloud", "/auth/device/start", "Authorization"):
        assert secret.encode() not in everything, secret
    assert not any(k.lower() in ("origin", "authorization") for k in headers)
    assert fake.inner_seen[0]["m"] == "POST" and fake.inner_seen[0]["p"] == "/auth/device/start"


def test_session_token_travels_only_inside_the_seal(sealed_env, monkeypatch):
    fake = FakeBroker()
    fake.respond = lambda inner: (200, json.dumps({"email": "a@b.c", "token_id": "t1", "label": "l",
                                                    "created_at": 1, "expires_at": 2000000000}))
    _install(monkeypatch, fake)
    info = client.get_session(DEFAULT_BROKER_URL, SESSION_TOKEN)
    assert info.email == "a@b.c"
    assert fake.inner_seen[0]["a"] == f"Bearer {SESSION_TOKEN}"
    url, headers, req_body, resp_body = fake.wire[0]
    assert SESSION_TOKEN.encode() not in url.encode() + json.dumps(headers).encode() + req_body + resp_body
    assert fake.inner_seen[0]["m"] == "GET" and fake.inner_seen[0]["p"] == "/cli/session"


def test_inner_status_is_preserved(sealed_env, monkeypatch):
    fake = FakeBroker()
    fake.respond = lambda inner: (429, json.dumps({"error": "rate_limited"}))
    _install(monkeypatch, fake)
    with pytest.raises(AccountError, match="rate limiting"):
        client.get_session(DEFAULT_BROKER_URL, SESSION_TOKEN)


def test_wrong_key_broker_fails_closed(sealed_env, monkeypatch):
    real, impostor = FakeBroker(), FakeBroker()
    monkeypatch.setattr(client, "_sealed_opener", lambda: impostor)
    monkeypatch.setattr(sealed, "PINNED_KEYS", real.pins())  # pinned: the real key
    with pytest.raises(Exception) as err:  # impostor cannot even decapsulate the request
        client.start_device(DEFAULT_BROKER_URL, "x")
    assert DEVICE_CODE not in str(err.value)


def test_tampered_response_is_rejected(sealed_env, monkeypatch):
    fake = FakeBroker(tamper=True)
    _install(monkeypatch, fake)
    with pytest.raises(sealed.SealedError, match="could not be authenticated") as err:
        client.start_device(DEFAULT_BROKER_URL, "x")
    assert DEVICE_CODE not in str(err.value)


@pytest.mark.parametrize("mutate", [
    lambda e: {**e, "v": 2},
    lambda e: {k: v for k, v in e.items() if k != "nonce"},
    lambda e: {**e, "extra": 1},
    lambda e: {**e, "nonce": "AA"},
    lambda e: {**e, "ct": "!!"},
])
def test_malformed_response_envelopes_are_rejected(mutate):
    fake = FakeBroker()
    req = sealed.seal("POST", "/auth/device/start", body=None, bearer=None, pins=fake.pins())

    class R:
        full_url = "x"
        data = req.body

        def header_items(self):
            return []

    out = json.loads(fake.open(R()).read())
    with pytest.raises(sealed.SealedError):
        req.open(json.dumps(mutate(out)).encode())


def test_a_response_for_another_request_cannot_be_opened():
    fake = FakeBroker()
    a = sealed.seal("POST", "/auth/device/start", body=None, bearer=None, pins=fake.pins())
    b = sealed.seal("POST", "/auth/device/start", body=None, bearer=None, pins=fake.pins())

    class R:
        full_url = "x"
        header_items = lambda self: []  # noqa: E731

    ra = R()
    ra.data = a.body
    with pytest.raises(sealed.SealedError):
        b.open(fake.open(ra).read())


